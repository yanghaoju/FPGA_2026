#ifndef FPT_ATTENTION_IP_PROFILE_HPP
#define FPT_ATTENTION_IP_PROFILE_HPP

// U126 freezes the Prefill geometry and uses a row-scaled signed-INT13
// Decode cache representation.
// Shape values are compile-time constants; do not replace them with runtime controls.
#define ATTENTION_IP_Q_HEADS 32
#define ATTENTION_IP_KV_HEADS 8
#define ATTENTION_IP_GQA_GROUP 4
#define ATTENTION_IP_HEAD_DIM 64
#define ATTENTION_IP_LOGICAL_SEQ 512
#define ATTENTION_IP_STORAGE_SEQ 512
#define ATTENTION_IP_TILE_K 32
#define ATTENTION_IP_ROWS_PER_BLOCK 4
#define ATTENTION_IP_STATIC_GQA_LANES 4
#define ATTENTION_IP_QK_PAR_D 32
#define ATTENTION_IP_PV_PAR_K 32
#define ATTENTION_IP_NORM_PAR_D 2
#define ATTENTION_IP_MEM_WORD_BITS 512
#define ATTENTION_IP_VALUES_PER_WORD 32
#define ATTENTION_IP_WORDS_PER_ROW 2
#define ATTENTION_IP_STATIC_FRONTIERS 16
#define ATTENTION_IP_BLOCKS_PER_FRONTIER 8
#define ATTENTION_IP_TAIL_PADDING 0
#define ATTENTION_IP_LAST_TILE_VALID_K 32
#define ATTENTION_IP_LOGICAL_Q_WORDS 32768
#define ATTENTION_IP_STORAGE_Q_WORDS 32768
#define ATTENTION_IP_LOGICAL_KV_WORDS 8192
#define ATTENTION_IP_STORAGE_KV_WORDS 8192

static_assert(ATTENTION_IP_Q_HEADS == ATTENTION_IP_KV_HEADS * ATTENTION_IP_GQA_GROUP, "GQA ratio mismatch");
static_assert(ATTENTION_IP_STORAGE_SEQ % ATTENTION_IP_TILE_K == 0, "storage must tile exactly");
static_assert(ATTENTION_IP_LOGICAL_SEQ % ATTENTION_IP_ROWS_PER_BLOCK == 0, "query blocks must be integral");
#endif
